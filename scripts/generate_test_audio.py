"""
Generates static test audio leveraging KokoroEngine.
"""
import os
import wave

from lite_assistant.engines.kokoro_engine import KokoroEngine

def main():
    print("Generating static test_audio.wav using KokoroEngine...")
    KokoroEngine.setup()
    engine = KokoroEngine()
    
    text = "This is a static test audio generated by Kokoro engine to verify the speech to text transcription."
    chunks = list(engine.generate_pcm(text, engine.get_default_voice()))
    
    # Combine chunks into a wav file
    audio_data = b"".join(chunks)
    
    tests_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'tests'))
    os.makedirs(tests_dir, exist_ok=True)
    wav_path = os.path.join(tests_dir, "test_audio.wav")
    
    with wave.open(wav_path, "wb") as wf:
        wf.setnchannels(1)
        wf.setsampwidth(2) # 16-bit
        wf.setframerate(24000)
        wf.writeframes(audio_data)
        
    print(f"Successfully generated {wav_path}")

if __name__ == "__main__":
    main()
